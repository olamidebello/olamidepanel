CREATE TABLE IF NOT EXISTS user_ids (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT NOT NULL PRIMARY KEY,
 username VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 salt CHAR(32) CHARACTER SET ascii NOT NULL,
 password CHAR(128) CHARACTER SET ascii NOT NULL,
 role VARCHAR(20) CHARACTER SET ascii NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 email VARCHAR(254) NOT NULL DEFAULT '',
 display_name VARCHAR(100) NOT NULL DEFAULT '',
 session_version BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS domains (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 owner BIGINT NOT NULL,
 name VARCHAR(253) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 created BIGINT NOT NULL,
 INDEX domains_owner (owner),
 CONSTRAINT domains_user FOREIGN KEY (owner) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 actor VARCHAR(64) NOT NULL,
 action TEXT NOT NULL,
 created BIGINT NOT NULL,
 INDEX audit_created (created)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
INSERT IGNORE INTO user_ids(id) SELECT id FROM users;

CREATE TABLE IF NOT EXISTS legal_acceptances (
 user_id BIGINT NOT NULL,
 version VARCHAR(32) NOT NULL,
 accepted_at BIGINT NOT NULL,
 PRIMARY KEY (user_id,version),
 CONSTRAINT legal_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS marketplace_vendors (
 user_id BIGINT NOT NULL PRIMARY KEY,
 enabled BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT vendor_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS hosting_plans (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 seller_id BIGINT NOT NULL DEFAULT 0,
 plan_kind VARCHAR(16) NOT NULL DEFAULT 'hosting',
 name VARCHAR(80) NOT NULL,
 description TEXT NOT NULL,
 price_cents BIGINT NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'USD',
 interval_name VARCHAR(16) NOT NULL DEFAULT 'monthly',
 disk_gb INT NOT NULL,
 bandwidth_gb INT NOT NULL,
 websites INT NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT FALSE,
 featured BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS hosting_orders (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 owner BIGINT NOT NULL,
 seller_id BIGINT NOT NULL DEFAULT 0,
 plan_id BIGINT NOT NULL,
 request_key VARCHAR(64) CHARACTER SET ascii NOT NULL,
 plan_snapshot TEXT NOT NULL,
 price_cents BIGINT NOT NULL,
 currency CHAR(3) NOT NULL,
 status VARCHAR(20) NOT NULL,
 note TEXT NOT NULL,
 operator_note TEXT,
 created BIGINT NOT NULL,
 updated BIGINT NOT NULL,
 UNIQUE KEY order_request (owner,request_key),
 INDEX order_status (status),
 CONSTRAINT order_owner FOREIGN KEY (owner) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT order_plan FOREIGN KEY (plan_id) REFERENCES hosting_plans(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payment_gateways (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 owner_id BIGINT NOT NULL,
 provider VARCHAR(32) NOT NULL,
 label VARCHAR(80) NOT NULL,
 mode VARCHAR(8) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT FALSE,
 credentials TEXT NOT NULL,
 updated BIGINT NOT NULL,
 INDEX gateway_owner (owner_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payment_transactions (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT NOT NULL UNIQUE,
 buyer_id BIGINT NOT NULL,
 seller_id BIGINT NOT NULL,
 gateway_id BIGINT NOT NULL,
 provider VARCHAR(32) NOT NULL,
 mode VARCHAR(8) NOT NULL,
 amount_cents BIGINT NOT NULL,
 currency CHAR(3) NOT NULL,
 state VARCHAR(24) NOT NULL,
 token VARCHAR(40) NOT NULL UNIQUE,
 provider_reference VARCHAR(200),
 checkout_url TEXT,
 created BIGINT NOT NULL,
 verified_at BIGINT,
 INDEX payment_buyer (buyer_id),
 INDEX payment_seller (seller_id),
 UNIQUE KEY payment_reference (gateway_id,provider_reference),
 CONSTRAINT payment_gateway FOREIGN KEY (gateway_id) REFERENCES payment_gateways(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS website_requests (
 domain_id BIGINT NOT NULL PRIMARY KEY,
 token VARCHAR(64) NOT NULL,
 state VARCHAR(24) NOT NULL,
 message VARCHAR(500) NOT NULL,
 title VARCHAR(100) NOT NULL,
 tagline VARCHAR(500) NOT NULL,
 updated BIGINT NOT NULL,
 CONSTRAINT website_domain FOREIGN KEY (domain_id) REFERENCES domains(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS user_mfa (
 user_id BIGINT PRIMARY KEY,
 secret_cipher TEXT NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT FALSE,
 recovery_hashes TEXT NOT NULL,
 last_step BIGINT NOT NULL DEFAULT -1,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS marketplace_stores (
 owner_id BIGINT NOT NULL PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 description VARCHAR(1000) NOT NULL DEFAULT '',
 contact_email VARCHAR(254) NOT NULL DEFAULT '',
 updated BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
